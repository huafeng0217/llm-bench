"""模型身份色：排行榜上「哪个点是哪个模型」靠它。

**为什么颜色要存在后端，而不是前端临时算**

颜色是**模型的属性**，不是"这一屏数据里的排序位置"。前端原来是在渲染时把模型名
排序、依次取 8 色 —— 那样「新加一个名字靠前的模型」会让榜上其他模型集体变色
（实测 6 个模型里 4 个变色），删掉一个更是全部变色。颜色一旦随数据变，
用户脑子里「绿色 = deepseek-flash」这种记忆就不成立，颜色就不算身份标记了。

现在：创建模型时分配一个颜色、存进 ``models.color``，此后**永不变**（删别的模型也不变）。
代价是要多一列（见 db.py 的迁移），换来的是颜色真能当身份用。

**色板怎么定的**（不是随手挑的）

圆点坐在浅灰轨道 ``--bg2`` = ``#eef1f6`` 上（``.ov-dist`` 的背景），
所以按这个底色校核：16 色对它的对比度**全部 ≥3.19**（WCAG 对图形对象的要求是 3:1；
换掉的两个老色原本是 2.47 和 3.00，都贴线或不够）。
两两可区分度用 ΔE76 当粗代理，**最小 29.9** —— 16 个色在色相环上只隔 22.5°，
只靠色相必然出现"两个看起来一样的红/蓝"（手挑版本实测撞到 ΔE 9.5），
所以明暗也参与区分：前 8 个是原来那套（观感延续），后 8 个是搜出来的。

用完 16 色就复用（按"用得最少"挑），因为一个榜上 17 个模型时点图本来也读不动了。
"""
from collections import Counter

# 16 色。前 8 个是原来那套（青色 #0f9b9b 压深成 #0d8a8a，橙色 #e0952f 换成同色系更深的
# #b9791e —— 那两个原本对比度不够）；后 8 个补在现有色相的空隙里。
PALETTE: list[str] = [
    "#4a7de0",   # 蓝   白 3.96 / 浅灰 3.50
    "#b9791e",   # 琥珀 白 3.61 / 浅灰 3.19
    "#22995c",   # 绿   白 3.63 / 浅灰 3.21
    "#c44b8a",   # 玫红 白 4.45 / 浅灰 3.93
    "#8b5cf6",   # 紫罗兰 白 4.23 / 浅灰 3.74
    "#0d8a8a",   # 青   白 4.18 / 浅灰 3.70
    "#d9534f",   # 红   白 3.96 / 浅灰 3.50
    "#6b7a90",   # 石板灰 白 4.36 / 浅灰 3.85
    "#84238e",   # 深紫 白 8.04 / 浅灰 7.10
    "#509315",   # 橄榄绿 白 3.80 / 浅灰 3.36
    "#2321df",   # 靛蓝 白 8.92 / 浅灰 7.88
    "#1f338b",   # 藏青 白 11.03 / 浅灰 9.74
    "#da22c3",   # 品红 白 4.20 / 浅灰 3.71
    "#843b15",   # 赭石 白 8.02 / 浅灰 7.09
    "#6f7020",   # 橄榄 白 5.23 / 浅灰 4.62
    "#831733",   # 酒红 白 9.83 / 浅灰 8.69
]


def pick(used) -> str:
    """挑一个颜色给新模型：优先没被用过的，都用过了就挑**用得最少**的。

    按"用得最少"而不是"从头再轮一遍"：删掉模型后它那个颜色会被下一个新模型捡回来，
    而不会出现「同一个颜色连着给两个新模型、另一个颜色空着没人用」。
    同分时按色板顺序取，保证同样的输入永远得到同样的结果（可测、可复现）。
    """
    counts = Counter(used)
    return min(PALETTE, key=lambda c: (counts.get(c, 0), PALETTE.index(c)))
