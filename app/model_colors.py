"""模型身份色：排行榜上「哪个点是哪个模型」靠它。

**为什么颜色要存在后端，而不是前端临时算**

颜色是**模型的属性**，不是"这一屏数据里的排序位置"。前端原来是在渲染时把模型名
排序、依次取 8 色 —— 那样「新加一个名字靠前的模型」会让榜上其他模型集体变色
（实测 6 个模型里 4 个变色），删掉一个更是全部变色。颜色一旦随数据变，
用户脑子里「绿色 = deepseek-flash」这种记忆就不成立，颜色就不算身份标记了。

现在：创建模型时分配一个颜色、存进 ``models.color``，此后**永不变**（删别的模型也不变）。
代价是要多一列（见 db.py 的迁移），换来的是颜色真能当身份用。

**色板怎么定的**（2026-10-26 重做，12 色）

圆点坐在浅灰轨道 ``--bg2`` = ``#eef1f6`` 上（``.ov-dist`` 的背景），
所以按这个底色校核：12 色对它的对比度**全部 ≥3.29**
（WCAG 对图形对象的要求是 3:1）。

**为什么要重做**：上一版色板是照**分类色**挑的 —— 同一屏里「分类点」和「模型点」大面积同色
（最严重的一个和「安全 / 对齐」完全相同，ΔE=0；另有 6 个 ΔE<14），
看起来就像"这个模型属于这个分类"。

现在模型色是**独立的 12 色**：色相均匀铺开（30° 一档，身份靠色相记），深浅交替拉开距离，
两两 ΔE76 **最小 29.5**；对 11 个分类色的 ΔE **最小
19.6** —— 两种点不会再混。

用完 12 色就复用（按"用得最少"挑），因为一个榜上 17 个模型时点图本来也读不动了。
"""
from collections import Counter

# 16 色。前 8 个是原来那套（青色 #0f9b9b 压深成 #0d8a8a，橙色 #e0952f 换成同色系更深的
# #b9791e —— 那两个原本对比度不够）；后 8 个补在现有色相的空隙里。
PALETTE: list[str] = [
    "#87271c",   # 6°
    "#cb6a2a",   # 24°
    "#877d1c",   # 54°
    "#356615",   # 96°
    "#1f981f",   # 120°
    "#358264",   # 157°
    "#235257",   # 186°
    "#41679f",   # 216°
    "#2f2fb1",   # 240°
    "#44246b",   # 267°
    "#b83db1",   # 303°
    "#661541",   # 327°
]


def pick(used) -> str:
    """挑一个颜色给新模型：优先没被用过的，都用过了就挑**用得最少**的。

    按"用得最少"而不是"从头再轮一遍"：删掉模型后它那个颜色会被下一个新模型捡回来，
    而不会出现「同一个颜色连着给两个新模型、另一个颜色空着没人用」。
    同分时按色板顺序取，保证同样的输入永远得到同样的结果（可测、可复现）。
    """
    counts = Counter(used)
    return min(PALETTE, key=lambda c: (counts.get(c, 0), PALETTE.index(c)))
